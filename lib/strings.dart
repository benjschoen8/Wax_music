import 'dart:ui' show PlatformDispatcher;

/// Tiny i18n: English by default; Traditional Chinese on zh devices, Simplified
/// on zh-Hans / zh-CN / zh-SG devices.
final _loc = PlatformDispatcher.instance.locale;
final bool zh = _loc.languageCode == 'zh';
final bool _hans =
    _loc.scriptCode == 'Hans' ||
    (_loc.scriptCode == null &&
        (_loc.countryCode == 'CN' || _loc.countryCode == 'SG'));

String tr(String en) => zh ? ((_hans ? _zhHans : _zhHant)[en] ?? en) : en;

/// Translate a template and fill `{name}` placeholders.
String trp(String en, Map<String, Object?> args) {
  return tr(en).replaceAllMapped(
    RegExp(r'\{(\w+)\}'),
    (m) => args.containsKey(m[1]) ? '${args[m[1]]}' : m[0]!,
  );
}

